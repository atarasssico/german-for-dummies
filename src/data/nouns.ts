export const NOUNS: Noun[] = ROWS.map(([word, gender, plural, en, topic, extra]) => ({
  id: slug(word),
  word,
  gender,
  plural,
  en,
  topic,
  level: (extra?.level ?? 'A2') as Level,
  hint: extra?.hint ?? genderHint(word),
  ...(extra?.gen ? { gen: extra.gen } : {}),
  ...(extra?.oblique ? { oblique: extra.oblique } : {}),
  ...(extra?.genS ? { genS: extra.genS } : {}),
}))

export const NOUN_BY_ID = new Map(NOUNS.map((n) => [n.id, n]))

export function noun(id: string): Noun {
  const n = NOUN_BY_ID.get(id)
  if (!n) throw new Error(`unknown noun: ${id}`)
  return n
}

