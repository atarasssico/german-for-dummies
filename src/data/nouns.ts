import type { Gender, Level, Noun } from '@/engine/grammar'

/**
 * Reliable gender-by-suffix rules. Used to show a "why this gender" hint on
 * corrections, and derived at load time rather than typed per noun.
 */
export const GENDER_RULES: Array<{ suffix: string; gender: Gender; note: string }> = [
  { suffix: 'ung', gender: 'f', note: '-ung is always feminine' },
  { suffix: 'heit', gender: 'f', note: '-heit is always feminine' },
  { suffix: 'keit', gender: 'f', note: '-keit is always feminine' },
  { suffix: 'schaft', gender: 'f', note: '-schaft is always feminine' },
  { suffix: 'tion', gender: 'f', note: '-tion is always feminine' },
  { suffix: 'tät', gender: 'f', note: '-tät is always feminine' },
  { suffix: 'ur', gender: 'f', note: '-ur is usually feminine' },
  { suffix: 'ik', gender: 'f', note: '-ik is usually feminine' },
  { suffix: 'ei', gender: 'f', note: '-ei is usually feminine' },
  { suffix: 'in', gender: 'f', note: '-in marks a female person' },
  { suffix: 'chen', gender: 'n', note: '-chen is always neuter, whatever the person' },
  { suffix: 'lein', gender: 'n', note: '-lein is always neuter' },
  { suffix: 'ment', gender: 'n', note: '-ment is usually neuter' },
  { suffix: 'um', gender: 'n', note: '-um is usually neuter' },
  { suffix: 'ling', gender: 'm', note: '-ling is always masculine' },
  { suffix: 'ismus', gender: 'm', note: '-ismus is always masculine' },
  { suffix: 'ist', gender: 'm', note: '-ist marks a masculine person noun' },
  { suffix: 'ant', gender: 'm', note: '-ant marks a masculine person noun' },
  { suffix: 'ent', gender: 'm', note: '-ent marks a masculine person noun' },
]

export function genderHint(word: string): string | undefined {
  for (const rule of GENDER_RULES) {
    if (word.length > rule.suffix.length + 1 && word.endsWith(rule.suffix)) return rule.note
  }
  return undefined
}

type Extra = Partial<Pick<Noun, 'gen' | 'oblique' | 'genS' | 'hint' | 'level'>>
type Row = [word: string, gender: Gender, plural: string, en: string, topic: string, extra?: Extra]

export function slug(word: string): string {
  return word
    .toLowerCase()
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss')
    .replace(/[^a-z0-9]+/g, '_')
}

